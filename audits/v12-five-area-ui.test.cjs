"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const html=fs.readFileSync(path.join(__dirname,"../production/dashboard-financeiro-v12-operacoes-homologada-20261023/index.html"),"utf8");
const match=html.match(/<script id="cr-v12-five-nav-20261107-js">([\s\S]*?)<\/script>/);
assert.ok(match,"enhancement script must exist");
assert.doesNotThrow(()=>new vm.Script(match[1],{filename:"cr-v12-five-nav-20261107.js"}));
const js=match[1];
for(const id of ["agora","corapro","cora","fin","hist"])assert.ok(js.includes('"'+id+'"'),"missing nav "+id);
for(const label of ["Visão Geral","Banco Cora","Gestão Financeira","Acertos","Histórico / Auditoria"])assert.ok(js.includes(label),"missing label "+label);
assert.ok(js.includes('oldAuditTab.hidden=true'),"redundant sixth primary tab must be hidden");
assert.ok(js.includes('window.r8Go=function(id){go(id);update(id)}'),"existing r8Go must be preserved");
assert.ok(js.includes('id==="conc"||id==="qual"?"hist"'),"audit and quality must stay accessible");
assert.ok(js.includes('id==="cost"?"cora"'),"cost tab must remain accessible");
assert.ok(js.includes('window.v12CapitalGo'),"capital shortcut must use established action");
assert.ok(js.includes('id="cr-v12-five-nav-20261107-js"')===false,"script should not inject itself");
assert.ok(js.includes("if(p.closest(\"details\")"),"do not double-wrap help");
assert.ok(js.includes('p.closest(\'[role="status"]\')'),"live status must stay visible");
assert.ok(js.includes('p.closest(\'[role="alert"]\')'),"critical alerts must stay visible");
assert.ok(js.includes('original=notice.textContent.trim()'),"security note original content retained");
assert.ok(js.includes('notice.insertAdjacentElement("afterend",d)'),"full security note stays accessible");
assert.doesNotMatch(js,/fetch\s*\(|api\s*\(|\bPOST\b|localStorage\./,"presentation addon must not access or mutate financial sources");
const acerto=html.slice(html.indexOf("function acertoCompleteText(rows,period)"),html.indexOf("async function copyAcerto()"));
assert.ok(acerto.includes("RATEIO DO LUCRO"));
assert.doesNotMatch(acerto,/🛠️ APOIO\s*\/\s*DI[ÁA]RIAS/);
assert.ok(html.includes("function crV12RemoveApoioResumo(value)"),"homologated historical scrubber must remain");
assert.ok(html.includes('id="cr-v12-five-nav-20261107"'));
assert.ok(html.includes('#cora>.panel:before{display:none!important}'),"long technical CSS banner should no longer occupy permanent space");
console.log("PASS: five primary areas, all legacy destinations available, static guidance collapsible, safety/status, acertos intact");
